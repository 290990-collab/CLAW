PLACEHOLDER_BLOCK = re.compile(r"\[TO FILL IN[^\]]*\]", re.DOTALL)


def fill(text: str, replacement: str) -> str:
    filled, n = PLACEHOLDER_BLOCK.subn(replacement, text)
    if n == 0:
        raise SystemExit("no [TO FILL IN] block found")
    return filled


def choices() -> tuple[profile.Profile, list[str], list[str], tuple[str, ...]]:
    """The questionnaire's answers: profile, roster, guides, hooks.

    A function and not variables inside `install()`: the installation plan is
    computed from the same choices, and two copies would diverge in silence.
    """
    prof = profile.load(FRAMEWORK / "profiles" / "software.toml")
    roster = profile.roster(prof, extras=[], drop=[])
    return prof, roster, profile.guides(FRAMEWORK, prof, roster), settings.HOOKS


def install(out: Path, orchestration: str = ORCHESTRATION) -> int:
    """Installs the fake project and returns the number of agents.

    `orchestration` stays out of `choices()`: the file plan does not change
    with it, only the guide's content and the settings do.
    """
    if out.exists():
        shutil.rmtree(out)
    (out / ".claude" / "agents").mkdir(parents=True)
    (out / ".claude" / "shared" / "core").mkdir(parents=True)
    (out / ".claude" / "output-styles").mkdir(parents=True)
    (out / ".claude" / "hooks").mkdir(parents=True)
    (out / "docs").mkdir(parents=True)

    prof, roster, guides, hooks = choices()

    (out / "CLAUDE.md").write_text(
        assemble.build_document(FRAMEWORK / "method", VERSION, PROJECT_SECTIONS),
        encoding="utf-8",
    )

    # The coordinator's guide: same mechanics, different recipient. It does not
    # go into CLAUDE.md, so subagents do not pay for it. The chosen
    # orchestration and the cycles declared by the profile are appended here, in
    # this order: they are orchestration, not execution.
    (out / ".claude" / "shared" / "orchestration.md").write_text(
        assemble.build_document(
            FRAMEWORK / "coordinator",
            VERSION,
            ROUTING,
            extra=[
                assemble.orchestration_file(FRAMEWORK, orchestration),
                *assemble.cycle_files(FRAMEWORK, prof.cycles),
            ],
        ),
        encoding="utf-8",
    )

    for name in roster:
        src = (FRAMEWORK / "agents" / f"{name}.md").read_text(encoding="utf-8")
        fm, method, domain = assemble.split_source(src)
        domain = fill(domain, DOMAIN[name])
        (out / ".claude" / "agents" / f"{name}.md").write_text(
            assemble.build_agent(fm, method, domain, VERSION), encoding="utf-8"
        )

    for rel in guides:
        text = (FRAMEWORK / "shared" / rel).read_text(encoding="utf-8")
        (out / ".claude" / "shared" / rel).write_text(fill(text, GUIDES[rel]), encoding="utf-8")

    for name in hooks:
        shutil.copy(FRAMEWORK / "hooks" / f"{name}.py", out / ".claude" / "hooks")

    # Profile and hooks together first, then on top of what the project already
    # has — nothing here, but the step is the same as on a real project: it is
    # the addition the manifest records, so the uninstall removes only that.
    framework_settings, _, conflicts = settings.merge(prof.settings, settings.hooks(hooks))
    if conflicts:
        raise SystemExit(f"profile and hooks conflict on: {', '.join(conflicts)}")
    framework_settings, _, conflicts = settings.merge(
        framework_settings, settings.ORCHESTRATION_SETTINGS.get(orchestration, {})
    )
    if conflicts:
        raise SystemExit(f"orchestration conflicts on: {', '.join(conflicts)}")
    merged, added, conflicts = settings.merge({}, framework_settings)
    if conflicts:
        raise SystemExit(f"settings.json conflicts on: {', '.join(conflicts)}")
    (out / ".claude" / "settings.json").write_text(
        json.dumps(merged, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )

    # How `claw-doctor` and `claw-sync` find the source again later,
    # and which profile the project was born with. The shape is decided by
    # `source.manifest`: the path is relative when the source sits inside the
    # project, so the file survives the clone.
    (out / ".claude" / "framework.json").write_text(
        json.dumps(
            source.manifest(out, FRAMEWORK, VERSION, prof.name, settings_added=added),
            indent=2,
        ) + "\n",
        encoding="utf-8",
    )

    for name in ("TODO.md", "status.md", "roadmap.md"):
        shutil.copy(FRAMEWORK / "templates" / name, out / "docs" / name)

    # Step 5: the TODO is born with the first real entry and the date. A
    # template copied and not filled in leaves the next session guessing.
    todo = out / "docs" / "TODO.md"
    todo.write_text(
        todo.read_text(encoding="utf-8")
        .replace("[TO FILL IN — the active task, one only]", FIRST_TASK)
        .replace(
            "[TO FILL IN — the next step, in dependency order]",
            FIRST_STEP,
        )
        .replace("[TO FILL IN — today's date]", date.today().isoformat())
        # No open decisions at birth: the example row goes, the header stays
        # to state the shape.
        .replace(DECISION_ROW, ""),
        encoding="utf-8",
    )

    roadmap = out / "docs" / "roadmap.md"
    roadmap.write_text(
        re.sub(
            r"^\| 1 \| \[TO FILL IN.*|^\*\*Order:\*\* \[TO FILL IN[^\]]*\]",
            lambda m: FIRST_GOAL if m.group().startswith("| 1 |") else "**Order:** 1",
            roadmap.read_text(encoding="utf-8"),
            flags=re.MULTILINE,
        ),
        encoding="utf-8",
    )

    # The lifecycle skills go where Claude Code looks for them, otherwise they
    # are not invocable in the project.
    for skill in doctor.LIFECYCLE_SKILLS:
        shutil.copytree(FRAMEWORK / "skills" / skill, out / ".claude" / "skills" / skill)

    # The reply style: `outputStyle` in the settings names it, this file defines
    # it. The project block is filled in at once, like every placeholder.
    style = (FRAMEWORK / "output-styles" / "reporting.md").read_text(encoding="utf-8")
    (out / ".claude" / "output-styles" / "reporting.md").write_text(
        fill(style, PROJECT_STYLE), encoding="utf-8"
    )

    print(f"installed: {len(roster)} agents, {len(guides)} guides -> {out}")
    return len(roster)


if __name__ == "__main__":
    install(Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT)
